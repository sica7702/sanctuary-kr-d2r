// Mechanical packaging of unchanged browser engines into a private Worker module.
import fs from 'node:fs';
import crypto from 'node:crypto';
const files=['rare-data.js','magic-data.js','build-demand-matrix.js','rare-appraisal-engine-v40.js'];
const sources=files.map(name=>({name,text:fs.readFileSync(new URL('../public/archive/'+name,import.meta.url),'utf8')}));
const hashes=Object.fromEntries(sources.map(s=>[s.name,crypto.createHash('sha256').update(s.text).digest('hex')]));
fs.writeFileSync(new URL('../ai-baseline-generated.mjs',import.meta.url),'// Generated by learning/build-baseline.mjs. Source assets are unchanged.\nconst window={};\n'+sources.map(s=>s.text).join('\n')+'\nexport const sourceHashes='+JSON.stringify(hashes)+';\nexport default window.SKR_RARE_ENGINE;\n');
